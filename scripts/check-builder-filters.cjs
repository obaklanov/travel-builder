const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict');
const root=process.argv[2]||path.resolve(__dirname,'..'),dist=path.join(root,'dist');
const engine=require(path.join(dist,'travel-builder-engine.js'));
const ctx=vm.createContext({URLSearchParams,location:{search:''}});
vm.runInContext(fs.readFileSync(path.join(dist,'travel-details.js'),'utf8'),ctx);
const countries=vm.runInContext('travelData',ctx),routes=(key,req)=>ctx.getFlightRoutes(key,req);
const data=Object.fromEntries(Object.entries(countries).map(([k,v])=>[k,{...v,continent:k==='spain'?'Europe':'Other'}]));
const base={destination:'spain',region:'',month:'2027-06',dateFlex:'0',days:'7',people:'1',budget:'',origin:'YYZ',season:'',arrival:'',lodging:'',food:'',transport:'',extras:''};
const now=new Date('2026-11-02T12:00:00');
const match=changes=>engine.match({...base,...changes},data,routes,now);
const first=match({})[0];assert(first);assert.equal(first.key,'spain');assert.equal(first.total,2280);assert.equal(first.start,'2027-06-01');assert.equal(first.end,'2027-06-07');
assert.equal(match({people:'2'})[0].total,3840,'Shared accommodation must not double');
assert.equal(match({lodging:'0',food:'0',transport:'0',extras:'0'})[0].total,1000,'Zero custom allowances are valid');
assert.equal(match({budget:'total:2000'}).length,0,'Strict ceiling');
assert(match({budget:'total:2000',budgetFlex:'0.2'}).length>0,'Explicit budget flexibility');
assert.equal(match({people:'2',budget:'person:1900'}).length,0,'Per-person budget converted to group ceiling');
assert(match({people:'2',budget:'person:2000'}).length>0);
assert.equal(match({flightHours:'2'}).length,0);assert.equal(match({flightBudget:'900'}).length,0);assert.equal(match({days:'1'}).length,0);
assert(match({arrival:'BCN'}).every(t=>t.route.code==='BCN'));
assert(match({region:'2'}).every(t=>t.regionIndex===2));
assert(engine.match({...base,destination:'continent:Europe'},data,routes,now).every(t=>t.key==='spain'));
assert.equal(match({style:'Adventure',passport:'US',advisory:'Normal precautions only'}).length,match({}).length,'Unsupported preferences must not silently affect matching');
assert.equal(engine.match(base,data,()=>[],now).length,0,'Missing route data');
assert.equal(engine.candidateMonths({...base,dateFlex:'1'},now).length,3);
assert.equal(engine.candidateMonths({...base,month:'2026-11',dateFlex:'2'},now).length,3,'Past months excluded');
assert(match({season:'B'}).every(t=>data[t.key].regions[t.regionIndex][1][5]==='B'));
const fake={test:{continent:'Europe',regions:[['Test','BWWWWWWWWWWW']],costs:[1,1,1,1]}};
assert.equal(engine.match({...base,destination:'test',month:'2027-01',days:'40',season:'B'},fake,()=>[{price:1,time:1,code:'ABC'}],now).length,0,'Check season across the entire trip');
const planner=vm.createContext({URLSearchParams,location:{search:'?country=spain&days=7&people=2&start=2027-06-01&returnTo=home&builderRegion=2&builderRate0=1000&builderRate1=99&builderRate2=0&builderRate3=12&builderRate4=8'}});
vm.runInContext(fs.readFileSync(path.join(dist,'travel-details.js'),'utf8'),planner);
const state=planner.getBudgetState('spain');assert.equal(state.people,2);assert.equal(state.regionChoice.index,2);assert.equal(state.rates[1],99);assert.equal(state.rates[2],0);assert.equal(state.departureDate,'2027-06-01');
const conf=vm.createContext({window:{}});vm.runInContext(fs.readFileSync(path.join(dist,'travel-builder-filter-options.js'),'utf8'),conf);
const defs=conf.window.TRAVEL_BUILDER_FILTERS;assert.equal(defs.length,39);assert.equal(new Set(defs.map(d=>d.id)).size,39);
for(const group of ['party','where','experience','budget','travel','needs'])assert(defs.some(d=>d.group===group));
for(const id of ['lodging','food','transport','extras','flightBudget','arrival'])assert(!defs.some(d=>d.id===id),'Planning-only control leaked into Designing');
assert.equal(match({earliest:'2027-06-12',latest:'2027-06-18'})[0].start,'2027-06-12');
assert.equal(match({earliest:'2027-06-12',latest:'2027-06-17'}).length,0);
assert.equal(match({earliest:'2027-07-01',latest:'2027-07-10'}).length,0,'Month and date constraints intersect');
const html=fs.readFileSync(path.join(dist,'index.html'),'utf8');const ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);assert.equal(new Set(ids).size,ids.length);assert(!html.includes('src="trip-start.js'));
console.log('PASS: 39 Designing definitions and six groups; route/region/continent filters; budgets and zero allowances; shared group costs; month windows and multi-month seasons; missing data; unsupported preferences; planner handoff; unique HTML IDs.');

assert.equal(match({people:'10'})[0].total,16320,'Ten-person calculation');
assert.equal(match({people:'11'}).length,0,'Reject unsupported group size');
assert.equal(match({people:'2.5'}).length,0,'Reject fractional group size');
assert.equal(defs.find(d=>d.id==='people').options.length,10);
assert.equal(defs.find(d=>d.id==='people').options.at(-1)[0],'10');

assert.equal(match({exclude:['country:spain']}).length,0,'Exclusion overrides selected country');
assert.equal(match({exclude:['continent:Europe']}).length,0,'Continent exclusion');
const madrid=engine.regionExclusionId('spain',data.spain.regions[0][0]);
const remaining=match({exclude:[madrid]});assert(remaining.length>0);assert(remaining.every(t=>t.regionIndex!==0),'Region exclusion retains other regions');
assert.equal(match({region:'0',exclude:[madrid]}).length,0,'Region exclusion overrides region selection');
const asiaData=Object.fromEntries(['japan','south-korea','thailand'].map(key=>[key,{...data[key],continent:'Asia'}]));
const asia=engine.match({...base,destination:'continent:Asia',exclude:['country:south-korea']},asiaData,routes,now);
assert(asia.length>0);assert(asia.every(t=>t.key!=='south-korea'),'Asia except South Korea');
assert.equal(engine.match({...base,destination:'continent:Asia',exclude:['country:south-korea','country:japan','country:thailand']},asiaData,routes,now).length,0);
assert.notEqual(engine.regionExclusionId('spain','Center'),engine.regionExclusionId('japan','Center'),'Region IDs are scoped to country');

assert.equal(engine.candidateMonths({...base,month:'2029-11'},now).length,1,'Three-year boundary included');
assert.equal(engine.candidateMonths({...base,month:'2029-12'},now).length,0,'Month beyond three years rejected');
assert.equal(engine.candidateMonths({...base,month:'2029-11',dateFlex:'2'},now).length,3,'Flexibility cannot extend past limit');
assert.equal(match({month:'2029-12'}).length,0,'No trips beyond the month horizon');

const durationOptions=defs.find(d=>d.id==='days').options;
assert.equal(durationOptions.find(([v])=>v==='14')[1],'2 weeks');
assert.equal(durationOptions.find(([v])=>v==='21')[1],'3 weeks');
assert.equal(durationOptions.find(([v])=>v==='20')[1],'20 days');
assert(durationOptions.some(([v])=>v==='90'));
assert.equal(match({days:'14'})[0].days,14);
assert.equal(match({days:'21'})[0].days,21);

